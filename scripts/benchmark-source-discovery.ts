import { mkdtemp, rm } from 'node:fs/promises';
import { platform, release, tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { getHeapStatistics } from 'node:v8';
import { runGit } from './source-discovery-benchmark/repository.ts';
import {
  entryCounts,
  deepDirectoryDepth,
  queryRepeats,
  repeats,
  shapes,
  wideDirectoryLimit,
} from './source-discovery-benchmark/config.ts';
import { measureRepository } from './source-discovery-benchmark/measure-repository.ts';
import type { BenchmarkResult } from './source-discovery-benchmark/config.ts';

async function main(): Promise<void> {
  const base = await mkdtemp(resolve(tmpdir(), 'codethread-discovery-bench-'));
  try {
    const gitVersion = (
        await runGit(base, resolve(base, 'empty.gitconfig'), ['--version'])
      )
        .toString('utf8')
        .trim(),
      results: BenchmarkResult[] = [];
    for (const entries of entryCounts)
      for (const shape of shapes)
        results.push(await measureRepository(base, shape, entries));
    process.stdout.write(
      `${JSON.stringify(
        {
          benchmark: 'CT-COMP-001 source inventory and selection',
          environment: {
            node: process.version,
            platform: platform(),
            osRelease: release(),
            git: gitVersion,
            cpuCount: process.env.NUMBER_OF_PROCESSORS ?? null,
            heapLimitMiB: Math.round(
              getHeapStatistics().heap_size_limit / (1024 * 1024),
            ),
            explicitGc: typeof global.gc === 'function',
          },
          repetitions: repeats,
          queryOperationsPerSample: queryRepeats,
          workload: { deepDirectoryDepth, wideDirectoryLimit },
          limits: {
            inventoryFiles: 1000,
            uniqueTrees: 128,
            treeVisits: 4096,
            treeEntries: 10000,
            metadataObjectBytes: 1048576,
            metadataBytes: 4194304,
            sourceFiles: 20,
            sourceBytesPerFile: 262144,
            sourceBytesTotal: 2097152,
          },
          partialInventory: {
            lowerTreeLimitReason: 'tree_limit',
            cancelledBeforeStartCode: 'CANCELLED',
          },
          results,
          note: 'Generated byte-identical source blobs in disposable local commits; setup time is excluded. RSS is sampled in the benchmark parent and is not a total system or child-process memory bound.',
        },
        null,
        2,
      )}\n`,
    );
  } finally {
    await rm(base, { recursive: true, force: true });
  }
}

void main().catch((error: unknown) => {
  process.stderr.write(
    `Discovery benchmark failed: ${error instanceof Error ? error.message : 'unknown error'}\n`,
  );
  process.exitCode = 1;
});
